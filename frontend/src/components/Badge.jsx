import React from 'react';

export default function Badge({
  children,
  variant = 'indigo', // indigo | emerald | purple | amber | rose | cyan | slate | blue
  size = 'md', // sm | md
  icon: Icon,
  className = '',
  id,
}) {
  const variantStyles = {
    indigo: 'bg-indigo-50 text-indigo-700 border-indigo-200',
    blue: 'bg-blue-50 text-blue-700 border-blue-200',
    emerald: 'bg-emerald-50 text-emerald-700 border-emerald-200',
    purple: 'bg-purple-50 text-purple-700 border-purple-200',
    amber: 'bg-amber-50 text-amber-700 border-amber-200',
    rose: 'bg-rose-50 text-rose-700 border-rose-200',
    cyan: 'bg-cyan-50 text-cyan-700 border-cyan-200',
    slate: 'bg-slate-100 text-slate-700 border-slate-200',
  };

  const sizeStyles = {
    sm: 'px-2 py-0.5 text-[11px]',
    md: 'px-2.5 py-1 text-xs',
  };

  return (
    <span
      id={id}
      className={`inline-flex items-center gap-1.5 font-medium rounded-md border ${sizeStyles[size]} ${variantStyles[variant] || variantStyles.indigo} ${className}`}
    >
      {Icon && <Icon className="w-3.5 h-3.5 shrink-0" />}
      <span>{children}</span>
    </span>
  );
}

